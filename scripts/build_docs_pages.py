def main() -> None:
    (DOCS / "reference").mkdir(parents=True, exist_ok=True)
    write_brand_assets()
    rules_path = DOCS / "reference" / "rules.md"
    rules_path.write_text(rules_page(), encoding="utf-8")
    print(f"wrote {rules_path.relative_to(REPO)} ({len(REGISTRY.all())} rules)")

    result = build_example()
    (DOCS / "example" / "dashboard.md").write_text(dashboard_page(), encoding="utf-8")
    pages = sorted((DOCS / "example").rglob("*.md"))
    print(f"wrote {len(pages)} example pages, score {result.score.total:g}")


if __name__ == "__main__":
    main()
