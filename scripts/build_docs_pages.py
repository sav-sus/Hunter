def build_example() -> object:
    """Render the example project's site into the documentation."""
    # read_git=False so these committed pages rebuild identically from any
    # checkout. Git dates would move them on every commit that touches the
    # example, and CI checks they have not drifted.
    result = run(EXAMPLE, as_of=AS_OF, read_git=False)

    target = DOCS / "example"
    if target.exists():
        shutil.rmtree(target)
    staging = DOCS / "_example_staging"
    if staging.exists():
        shutil.rmtree(staging)

    write_site(result, staging)
    shutil.move(str(staging / "docs"), str(target))
    shutil.rmtree(staging)

    # The example's own index becomes a page inside the docs site, so the
    # section can have a framing page of its own at index.md.
    (target / "index.md").rename(target / "index-page.md")
    (target / "index.md").write_text(example_intro(result), encoding="utf-8")

    # The example's mkdocs.yml is not wanted inside the documentation tree.
    for stray in target.glob("mkdocs.yml"):
        stray.unlink()

    return result


def write_brand_assets() -> None:
    """Copy the palette and the logo into the documentation tree.

    The stylesheet is generated from ``hunter.brand``, the same module the
    report dashboard reads, so the documentation cannot drift away from the
    product's own colours.
    """
    from hunter.brand import ASSETS
    from hunter.emit.theme import BRAND_CSS

    assets = DOCS / "assets"
    assets.mkdir(parents=True, exist_ok=True)
    (assets / "rittman.css").write_text(BRAND_CSS, encoding="utf-8")
    for name in ("rittman-analytics.png", "favicon.ico"):
        (assets / name).write_bytes((ASSETS / name).read_bytes())
    print(f"wrote {assets.relative_to(REPO)}/ (palette and logo)")


