#!/usr/bin/env python3
"""Generate the documentation pages that must never be hand-written.

Two of them:

* ``docs/reference/rules.md`` -- every rule, from the registry. Hand-maintaining
  a list of 77 rules guarantees it goes stale, and a stale rules reference is
  worse than none because someone will act on it.
* ``docs/example/`` -- the real output of running Hunter against
  ``examples/tiny-shop``. A screenshot would go stale the same way; this is the
  actual thing.

Run it after adding a rule or changing the example:

    python scripts/build_docs_pages.py

CI regenerates and fails if the result differs, so neither can drift.
"""

from __future__ import annotations

import datetime as dt
import shutil
import sys
from pathlib import Path

REPO = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(REPO / "src"))

import hunter.checks  # noqa: E402, F401  registers every rule
from hunter.checks.base import REGISTRY  # noqa: E402
from hunter.emit.markdown import write_site  # noqa: E402
from hunter.emit.plain import (  # noqa: E402
    DIMENSION_EXPLANATIONS,
    DIMENSION_HEADINGS,
    severity_label,
)
from hunter.enums import Dimension  # noqa: E402
from hunter.run import run  # noqa: E402

EXAMPLE = REPO / "examples" / "tiny-shop"
DOCS = REPO / "docs"

#: Pinned so the example output never changes with the calendar.
AS_OF = dt.date(2026, 9, 8)


def rules_page() -> str:
    """Every rule, grouped by the area it scores."""
    lines = [
        "# Every rule",
        "",
        f"Hunter has {len(REGISTRY.all())} rules across "
        f"{len({rule.dimension for rule in REGISTRY.all()})} areas. This page is "
        "generated from the rules themselves, so it cannot go stale.",
        "",
        "Each rule can be switched off, reweighted or re-graded in a project's "
        "`hunter.yml`. Doing so needs a reason, and that reason is published on "
        "the conventions page of whatever the rule was run against.",
        "",
        "## What the columns mean",
        "",
        "| Column | Meaning |",
        "|---|---|",
        "| Rule | The identifier to use in `hunter.yml` and in the register |",
        "| How serious | What Hunter calls it in plain words. Only the most serious "
        "can fail a build in gate mode |",
        "| Points | What it deducts before weighting. Scaled up where more depends "
        "on the object, and scaled down for a partial gap |",
        "| Needs | The data the rule cannot run without. A rule whose data is "
        "absent is skipped, and its area says so |",
        "",
    ]

    for dimension in Dimension:
        rules = REGISTRY.by_dimension(dimension)
        heading = DIMENSION_HEADINGS[dimension]
        lines += [f"## {heading}", "", DIMENSION_EXPLANATIONS[dimension], ""]
        if not rules:
            lines += [
                "No rules yet. This area needs warehouse access, which is not read "
                "at this version, so it is excluded from the score and its weight "
                "shared across the others.",
                "",
            ]
            continue

        lines += [
            "| Rule | How serious | Points | Needs |",
            "|---|---|---|---|",
        ]
        for rule in rules:
            needs = ", ".join(rule.requires) or "nothing"
            lines.append(
                f"| `{rule.id}` | {severity_label(rule.severity)} | {rule.points:g} | {needs} |"
            )
        lines.append("")

        for rule in rules:
            lines += [
                f"### `{rule.id}`",
                "",
                f"**Reports**: {rule.title}",
                "",
                f"**Says**: {rule.consequence}",
                "",
            ]
            notes = []
            if not rule.exposure_weighted:
                notes.append(
                    "Not weighted by what depends on the object: this is about the "
                    "repository rather than one table's reach."
                )
            if rule.confidence < 1.0:
                notes.append(
                    f"Reported with a confidence of at most {rule.confidence:g}. "
                    "Below the configured floor it becomes a suggestion and is left "
                    "out of the score."
                )
            if rule.about_coverage:
                notes.append(
                    "Reports what Hunter could not check rather than what the "
                    "repository got wrong, so it never counts as a gap."
                )
            if rule.points == 0:
                notes.append("Deducts nothing. It is there to be read, not scored.")
            if notes:
                lines += ["", *[f"- {note}" for note in notes], ""]

    lines += [
        "---",
        "",
        "_Generated by `scripts/build_docs_pages.py`. Do not edit by hand._",
        "",
    ]
    return "\n".join(lines)


